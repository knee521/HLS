"""Calibrate on training data, select scaling on validation data, export HLS constants."""

import argparse
import json
import logging
import math

import numpy as np
import torch

from common.project import ROOT, configure_logging, read_config, sha256, write_json
from common.quantization import QuantizedMLP, round_symmetric
from train.model import dataset, load_model


def weight_fraction(weights: np.ndarray) -> int:
    maximum = float(np.abs(weights).max())
    if maximum > 127:
        raise ValueError("Weights cannot be represented in the selected int8 format")
    return 15 if maximum == 0 else max(0, min(15, math.floor(math.log2(127 / maximum))))


def export_header(model: QuantizedMLP, model_hash: str) -> None:
    folder = ROOT / "hls"
    folder.mkdir(exist_ok=True)
    lines = [
        "// Generated by train.export_quant; do not edit.",
        f"// model SHA256: {model_hash}",
        "#ifndef EXP3_WEIGHTS_H",
        "#define EXP3_WEIGHTS_H",
        '#include "nn_infer.h"',
        f"static const int REQUANT_SHIFT = {model.shift};",
    ]
    for name, values, ctype in [
        ("W1", model.w1, "weight_t"),
        ("B1", model.b1, "score_t"),
        ("W2", model.w2, "weight_t"),
        ("B2", model.b2, "score_t"),
    ]:
        shape = "".join(f"[{size}]" for size in values.shape)
        lines.append(f"static const {ctype} {name}{shape} = {{")
        if values.ndim == 2:
            lines.extend("    {" + ",".join(map(str, row.tolist())) + "}," for row in values)
        else:
            lines.append("    " + ",".join(map(str, values.tolist())))
        lines.append("};")
    lines.append("#endif")
    (folder / "weights.h").write_text("\n".join(lines) + "\n", encoding="ascii")


def load_quantized() -> QuantizedMLP:
    config = json.loads((ROOT / "model/quant_config.json").read_text(encoding="utf-8"))
    arrays = np.load(ROOT / "model/quantized.npz")
    model = QuantizedMLP(
        arrays["w1"],
        arrays["b1"],
        arrays["w2"],
        arrays["b2"],
        config["fw1"],
        config["fw2"],
        config["fh"],
    )
    model.verify()
    return model


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default="configs/baseline.json")
    args = parser.parse_args()
    configure_logging()
    config = read_config(args.config)
    torch.set_num_threads(config["cpu_threads"])
    model = load_model()
    pixels, labels = dataset(True)
    indices = np.load(ROOT / "model/split_indices.npz")
    calibration = pixels[indices["calibration"]]
    validation = pixels[indices["validation"]].numpy()
    validation_labels = labels[indices["validation"]].numpy()
    with torch.inference_mode():
        hmax = float(torch.relu(model.fc1(calibration.float() / 256)).max())
    if hmax <= 0:
        raise ValueError("Degenerate hidden activations")
    w1, b1 = model.fc1.weight.detach().numpy(), model.fc1.bias.detach().numpy()
    w2, b2 = model.fc2.weight.detach().numpy(), model.fc2.bias.detach().numpy()
    fw1, fw2 = weight_fraction(w1), weight_fraction(w2)
    initial_fh = max(0, min(15, 8 + fw1, math.floor(math.log2(255 / hmax))))
    candidates = sorted({max(0, min(15, 8 + fw1, initial_fh + delta)) for delta in [-1, 0, 1]})
    trials = []
    models = []
    for fh in candidates:
        quantized = QuantizedMLP(
            round_symmetric(w1 * 2**fw1),
            round_symmetric(b1.astype(np.float64) * 2 ** (8 + fw1)),
            round_symmetric(w2 * 2**fw2),
            round_symmetric(b2.astype(np.float64) * 2 ** (fh + fw2)),
            fw1,
            fw2,
            fh,
        )
        bounds = quantized.verify()
        prediction, _, _, saturated = quantized.infer(validation)
        accuracy = float((prediction == validation_labels).mean())
        trials.append(
            {
                "fh": fh,
                "validation_accuracy": accuracy,
                "saturated": saturated,
                "saturation_fraction": saturated / (len(validation) * 32),
            }
        )
        models.append((accuracy, -saturated, quantized, bounds))
        logging.info("fh=%d validation=%.5f saturated=%d", fh, accuracy, saturated)
    _, _, chosen, bounds = max(models, key=lambda item: (item[0], item[1]))
    np.savez(ROOT / "model/quantized.npz", w1=chosen.w1, b1=chosen.b1, w2=chosen.w2, b2=chosen.b2)
    export_header(chosen, sha256("model/best.pt"))
    write_json(
        "model/quant_config.json",
        {
            "fw1": fw1,
            "fw2": fw2,
            "fh": chosen.fh,
            "shift": chosen.shift,
            "input_scale": "1/256",
            "weight_layout": "output,input",
            "weight_bits": 8,
            "accumulator_bits": 32,
            "activation_bits": 8,
            "rounding": "nearest_ties_away_from_zero",
            "activation_saturation": [0, 255],
            "model_sha256": sha256("model/best.pt"),
            "weights_sha256": sha256("hls/weights.h"),
            "quantized_sha256": sha256("model/quantized.npz"),
            "split_sha256": sha256("model/split_indices.npz"),
            "calibration_count": len(calibration),
            "calibration_hmax": hmax,
            "selection_data": "validation_only",
            "trials": trials,
            "bounds": bounds,
        },
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
